 assert.equal(await page.evaluate(()=>localStorage.getItem('untold-motion')),'paused');
 results.push('Motion pause preference is stored locally.');
 console.log('Core flows passed. Checking the official WhatsApp without sending.');
 await context.close();
 const businessContext=await browser.newContext({viewport:{width:1440,height:900}});
 const bp=await businessContext.newPage();bp.setDefaultTimeout(15000);bp.on('pageerror',e=>errors.push(e.message));
 await bp.addInitScript(()=>{window.open=url=>{window.__testWhatsappTarget=url;return null;};});
 await bp.route('https://wa.me/**',r=>r.abort());
 await bp.goto('http://127.0.0.1:5173/?contato=1',{waitUntil:'domcontentloaded'});
 await bp.waitForFunction(()=>document.getElementById('contact-dialog').open);
 await bp.locator('#contact-name').fill('Teste de integração');
 await bp.locator('#contact-email').fill('qa@example.test');
 await bp.locator('#contact-message').fill('Este é um briefing de teste que não será enviado.');
 await bp.locator('#contact-submit').click();
 await bp.waitForFunction(()=>!!window.__testWhatsappTarget);
 const outgoing=await bp.evaluate(()=>window.__testWhatsappTarget);
 assert.ok(outgoing.startsWith('https://wa.me/5528920036176?text='));
 assert.ok(new URL(outgoing).searchParams.get('text').includes('Teste de integração'));
 assert.equal(await bp.locator('#contact-channel-link').getAttribute('href'),outgoing);
 await bp.screenshot({path:'qa/contact-desktop.png'});
