 results.push('Mobile menu opens, contains keyboard focus, and closes with Escape.');
 await page.locator('.hero [data-contact]').click();
 await page.locator('#contact-submit').click();
 assert.equal(await page.locator('#contact-name').getAttribute('aria-invalid'),'true');
 await page.locator('#contact-name').fill('Teste do site');
 await page.locator('#contact-email').fill('qa@example.test');
 await page.locator('#contact-message').fill('Quero um site para apresentar a identidade da minha marca.');
 await page.locator('#contact-submit').click();
 await page.waitForFunction(()=>document.getElementById('form-status').textContent.length>0);
 assert.ok(await page.locator('#form-status').innerText());
 assert.equal(await page.locator('#brief-download').isVisible(),true);
 const brief=await page.locator('#brief-download').evaluate(async a=>await (await fetch(a.href)).text());
 assert.ok(brief.includes('Teste do site')&&brief.includes('qa@example.test'));
 await page.screenshot({path:'qa/contact-mobile.png'});
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.activeElement===document.querySelector('.hero [data-contact]'));
 assert.ok(await page.locator('.hero [data-contact]').evaluate(b=>b===document.activeElement));
 results.push('Briefing validates each field and produces the actual downloadable text; no fake send.');
 await page.locator('[data-study="campo"]').click();
 assert.ok(await page.locator('#study-dialog').evaluate(d=>d.open));
 assert.ok(page.url().includes('experimento=campo'));
 await page.locator('#intensity').focus();await page.keyboard.press('End');
 assert.equal(await page.locator('#intensity').inputValue(),'100');
 await page.getByRole('button',{name:'Pausar experimento',exact:true}).click();
 assert.equal(await page.locator('#detail-pause').getAttribute('aria-pressed'),'true');
 await page.getByRole('button',{name:'Recomeçar',exact:true}).click();
 assert.equal(await page.locator('#intensity').inputValue(),'55');
 await page.screenshot({path:'qa/experiment-mobile.png'});
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>!location.search.includes('experimento='));
 assert.equal(page.url().includes('experimento='),false);
 results.push('Experiment opens, has a shareable URL, intensity, pause, reset and keyboard close.');
 await page.goto('http://127.0.0.1:5173/?experimento=ritmo',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.getElementById('study-dialog').open);
 assert.equal(await page.locator('#study-dialog-title').innerText(),'Ritmo');
 await page.keyboard.press('Escape');
 results.push('Direct experiment URLs load the corresponding interaction.');
 await page.setViewportSize({width:1440,height:900});
