 assert.equal(await page.locator('h1').innerText(),'Sites para o\nseu próximo\ncapítulo.');
 assert.ok(['live','poster'].includes(await page.locator('#hero-visual').getAttribute('data-scene-state')));
 results.push('Desktop loads with a real 3D scene or its original vector fallback.');
