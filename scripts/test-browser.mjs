 assert.equal(await page.locator('#hero-visual').getAttribute('data-scene-state'),'poster');
 assert.equal(await page.locator('#brand-canvas').isVisible(),false);
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.mark-poster')).opacity==='1');
 results.push('GPU context loss restores the original poster and removes the inactive canvas from keyboard navigation.');
 for(const width of [1440,1024,820,768,390,320]){
  await page.setViewportSize({width,height:width<640?844:900});
  await page.waitForTimeout(180);
  const bounds=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth}));
  assert.ok(bounds.width<=bounds.viewport+1,JSON.stringify(bounds));
 }
 results.push('No horizontal document overflow at 1440, 1024, 820, 768, 390 and 320 px.');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Abrir menu',exact:true}).click();
 assert.ok(await page.locator('#menu-dialog').evaluate(d=>d.open));
 assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'true');
 await page.keyboard.press('Tab');
 assert.ok(await page.evaluate(()=>document.getElementById('menu-dialog').contains(document.activeElement)));
